// Generates the SQL seed for built-in experiences from the same TypeScript definitions the app uses.
// Usage: npx tsx scripts/seed-sql.ts > ../supabase/migrations/<timestamp>_pp_seed_builtin.sql
import { ALL_EXPERIENCES as EXPERIENCES } from '../src/experiences';
import { validateExperience, SCHEMA_VERSION } from '../src/engine/schema';

const out: string[] = ['-- Built-in experiences (generated by web/scripts/seed-sql.ts; do not edit by hand).',
  '-- Each run inserts a new version only when the content changed, so published versions stay immutable.'];
for (const e of EXPERIENCES) {
  const r = validateExperience(e);
  if (!r.ok) throw new Error(`${e.id}: ${r.errors.join('; ')}`);
  const json = JSON.stringify(r.experience).replace(/\$/g, '\\u0024');
  out.push(`do $seed$
declare eid uuid; c jsonb := $j$${json}$j$::jsonb; last jsonb;
begin
  insert into pp.experiences(slug, title, visibility, status, built_in) values ('${e.id}', c->>'title', 'public', 'published', true)
    on conflict (slug) do update set title = excluded.title, updated_at = now() returning id into eid;
  select content into last from pp.experience_versions where experience_id = eid order by version desc limit 1;
  if last is distinct from c then
    insert into pp.experience_versions(experience_id, version, content, schema_version)
      values (eid, coalesce((select max(version) from pp.experience_versions where experience_id = eid), 0) + 1, c, ${SCHEMA_VERSION});
  end if;
end $seed$;`);
}
console.log(out.join('\n\n'));
